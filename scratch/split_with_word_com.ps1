Stop-Process -Name WINWORD -Force -ErrorAction SilentlyContinue
Start-Sleep -Milliseconds 500

$masterPath = 'd:\Users\anshp\Final year project\Major-Project\report\Major_Project_Report_Final_Updated.docx'
$partAPath  = 'd:\Users\anshp\Final year project\Major-Project\report\Part A_26AI09.docx'
$partBPath  = 'd:\Users\anshp\Final year project\Major-Project\report\Part B_26AI09.docx'
$partABatch = 'd:\Users\anshp\Final year project\Major-Project\report\Part A_Batch_number.docx'
$partBBatch = 'd:\Users\anshp\Final year project\Major-Project\report\Part B_Batch_number.docx'

$word = New-Object -ComObject Word.Application
$word.Visible = $false
$word.DisplayAlerts = 0

try {
    # ---------------- 1. GENERATE PART A ----------------
    Write-Host "Opening master for Part A..."
    $docA = $word.Documents.Open($masterPath)
    
    # Find CHAPTER 1
    $findA = $docA.Content.Find
    $findA.ClearFormatting()
    if ($findA.Execute("CHAPTER 1")) {
        $ch1Start = $findA.Parent.Start
        Write-Host "Found CHAPTER 1 at char position $ch1Start"
        $delRangeA = $docA.Range($ch1Start, $docA.Content.End)
        $delRangeA.Delete()
        Write-Host "Deleted body elements for Part A"
    } else {
        throw "Could not find CHAPTER 1 in master!"
    }
    
    $docA.SaveAs([ref]$partAPath)
    $docA.SaveAs([ref]$partABatch)
    $pagesA = $docA.ComputeStatistics(2)
    Write-Host "Part A Saved! Pages: $pagesA"
    $docA.Close(0)
    
    # ---------------- 2. GENERATE PART B ----------------
    Write-Host "`nOpening master for Part B..."
    $docB = $word.Documents.Open($masterPath)
    
    $findB = $docB.Content.Find
    $findB.ClearFormatting()
    if ($findB.Execute("CHAPTER 1")) {
        $ch1Start = $findB.Parent.Start
        Write-Host "Found CHAPTER 1 at char position $ch1Start"
        $delRangeB = $docB.Range(0, $ch1Start)
        $delRangeB.Delete()
        Write-Host "Deleted preliminary elements for Part B"
    } else {
        throw "Could not find CHAPTER 1 in master!"
    }
    
    # Configure headers and footers for all sections in Part B
    for ($s = 1; $s -le $docB.Sections.Count; $s++) {
        $sec = $docB.Sections.Item($s)
        
        # Clear and unlink header
        $hdr = $sec.Headers.Item(1)
        $hdr.LinkToPrevious = $false
        $hdr.Range.Text = ""
        
        # Set footer to centered Arabic page number starting at 1
        $ftr = $sec.Footers.Item(1)
        $ftr.LinkToPrevious = $false
        $ftr.Range.Text = ""
        $ftr.Range.ParagraphFormat.Alignment = 1 # Center
        $hdr.PageNumbers.NumberStyle = 0 # wdPageNumberStyleArabic
        if ($s -eq 1) {
            $hdr.PageNumbers.RestartNumberingAtSection = $true
            $hdr.PageNumbers.StartingNumber = 1
        }
        $docB.Fields.Add($ftr.Range, -1, "PAGE", $true) | Out-Null
    }
    
    $docB.SaveAs([ref]$partBPath)
    $docB.SaveAs([ref]$partBBatch)
    $pagesB = $docB.ComputeStatistics(2)
    Write-Host "Part B Saved! Pages: $pagesB"
    $docB.Close(0)
    
    Write-Host "`nBoth parts cleanly generated by Word COM!"
} finally {
    $word.Quit()
    [System.Runtime.Interopservices.Marshal]::ReleaseComObject($word) | Out-Null
}
